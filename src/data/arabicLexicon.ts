// Normalized helper for dictionary indexing
export function norm(str: string): string {
  return str
    .replace(/[\u064B-\u065F\u0670\u0640]/g, '') // remove tashkeel & tatweel
    .replace(/[أإآٱٲٳ]/g, 'ا')
    .replace(/ة/g, 'ه')
    .replace(/ى/g, 'ي')
    .replace(/[\u200B-\u200F\uFEFF\u00AD\u202A-\u202E]/g, '')
    .trim()
    .toLowerCase();
}

